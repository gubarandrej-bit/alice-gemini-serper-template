export function detectModeCommand(rawText) {
  const cmd = normalizeCommand(rawText);

  if (/^(режимы|какие есть режимы|какие режимы|список режимов|выбрать режим)$/.test(cmd)) {
    return {
      type: "list",
      reply:
        "Доступны шесть режимов: «обычный режим», «режим переводчика», «детский режим» для сказок, «режим викторины», «практика английского» и «режим идей». Какой включить?"
    };
  }

  if (/^(режим переводчика|включи переводчик|включить переводчик|переводчик)$/.test(cmd)) {
    return {
      type: "switch",
      mode: "translator",
      sound: ALICE_SOUNDS.ping,
      reply:
        "Включён режим переводчика. Произнесите любую фразу по-русски, и я переведу её на английский — или наоборот. Чтобы вернуться, скажите «обычный режим»."
    };
  }

  if (/^(детский режим|режим сказочника|режим сказки|включи сказку|сказочник)$/.test(cmd)) {
    return {
      type: "switch",
      mode: "storyteller",
      sound: ALICE_SOUNDS.harp,
      reply:
        "Включён режим сказочника! Можем сочинить интерактивную сказку с выбором сюжета или поговорить о том, как устроен мир. Про кого придумаем историю?"
    };
  }

  if (/^(режим викторины|включи викторину|сыграем в викторину|давай поиграем в викторину|викторина)$/.test(cmd)) {
    return {
      type: "switch",
      mode: "quiz",
      sound: ALICE_SOUNDS.gameBoot,
      reply:
        "Включён режим викторины! Назовите любимую тему — космос, кино, география, история — или скажите «любая тема», и я задам первый вопрос."
    };
  }

  if (/^(практика английского|учитель английского|режим английского|английский диалог|тренировка английского)$/.test(cmd)) {
    return {
      type: "switch",
      mode: "coach",
      sound: ALICE_SOUNDS.ping,
      reply:
        "Включён режим практики английского! Давайте поболтаем: Hello! How is your day going today? Чтобы выйти, скажите «обычный режим»."
    };
  }

  if (/^(режим идей|генератор идей|мозговой штурм|подкинь идеи|придумай идеи)$/.test(cmd)) {
    return {
      type: "switch",
      mode: "brainstorm",
      sound: ALICE_SOUNDS.ping,
      reply:
        "Включён режим генератора идей! Скажите, для чего нужны варианты — например, что приготовить из продуктов в холодильнике или что подарить другу."
    };
  }

  if (/^(обычный режим|стандартный режим|выключи режим|выключи переводчик|выключи викторину|выключи сказку|хватит играть)$/.test(cmd)) {
    return {
      type: "switch",
      mode: "assistant",
      reply: "Вернулась в обычный режим помощника. О чём хотите спросить?"
    };
  }

  return null;
}

export function detectModeAnswerSound(mode, answerText) {
  if (
    mode === "quiz" &&
    /^(правильно|верно|точно|отлично|молодец|браво)(?=\s|[.,!?;:—–-]|$)/i.test(String(answerText || "").trim())
  ) {
    return ALICE_SOUNDS.gameWin;
  }
  return "";
}

export function getModeLabel(mode) {
  return MODE_DESCRIPTIONS[mode] || MODE_DESCRIPTIONS.assistant;
}

export function buildSystemPrompt({ timezone, mode = "assistant", userProfile = {} } = {}) {
  const tz = typeof timezone === "string" && timezone.trim() ? timezone.trim() : "Europe/Moscow";
  let dateLabel = "";
  try {
    dateLabel = new Intl.DateTimeFormat("ru-RU", {
      timeZone: tz,
      weekday: "long",
      year: "numeric",
      month: "long",
      day: "numeric"
    }).format(new Date());
  } catch {
    dateLabel = new Intl.DateTimeFormat("ru-RU", {
      timeZone: "Europe/Moscow",
      weekday: "long",
      year: "numeric",
      month: "long",
      day: "numeric"
    }).format(new Date());
  }

  const base = MODE_PROMPTS[mode] || MODE_PROMPTS.assistant;
  const parts = [base];

  if (mode === "assistant") {
    if (userProfile?.style === "short") {
      parts.push("Отвечай максимально лаконично: строго 1–2 коротких предложения по сути.");
    } else if (userProfile?.style === "detailed") {
      parts.push("Отвечай обстоятельно и развёрнуто: 4–6 предложений с полезными деталями.");
    } else {
      parts.push("Отвечай сразу по сути без вводных фраз: обычно 1–3 коротких предложения (до 45 слов).");
    }
  }

  if (userProfile?.name) {
    parts.push(`Пользователя зовут ${userProfile.name} (используй имя уместно и ненавязчиво).`);
  }

  if (userProfile?.city) {
    parts.push(`Город пользователя по умолчанию: ${userProfile.city}.`);
  }

  parts.push(`Сегодняшняя дата: ${dateLabel}.`);
  return parts.join(" ");
}
