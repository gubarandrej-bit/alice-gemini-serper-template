export function detectModeCommand(rawText) {
  const cmd = normalizeCommand(rawText);

  if (/^(режимы|какие есть режимы|какие режимы|список режимов|выбрать режим)$/.test(cmd)) {
    return {
      type: "list",
      reply:
        "Доступны четыре режима: «обычный режим», «режим переводчика», «детский режим» для сказок и простых объяснений, и «режим викторины». Какой включить?"
    };
  }

  if (/^(режим переводчика|включи переводчик|включить переводчик|переводчик)$/.test(cmd)) {
    return {
      type: "switch",
      mode: "translator",
      reply:
        "Включён режим переводчика. Произнесите любую фразу по-русски, и я переведу её на английский — или наоборот. Чтобы вернуться, скажите «обычный режим»."
    };
  }

  if (/^(детский режим|режим сказочника|режим сказки|включи сказку|сказочник)$/.test(cmd)) {
    return {
      type: "switch",
      mode: "storyteller",
      reply:
        "Включён режим сказочника! Можем сочинить интерактивную сказку с выбором сюжета или просто поговорить о том, как устроен мир. Про кого придумаем историю?"
    };
  }

  if (/^(режим викторины|включи викторину|сыграем в викторину|давай поиграем в викторину|викторина)$/.test(cmd)) {
    return {
      type: "switch",
      mode: "quiz",
      reply:
        "Включён режим викторины! Назовите любимую тему — например, космос, кино, география или история — или скажите «любая тема», и я задам первый вопрос."
    };
  }

  if (/^(обычный режим|стандартный режим|выключи режим|выключи переводчик|выключи викторину|выключи сказку|хватит играть)$/.test(cmd)) {
    return {
      type: "switch",
      mode: "assistant",
      reply: "Вернулась в обычный режим помощника. О чём хотите спросить?"
    };
  }

  return null;
}

export function getModeLabel(mode) {
  return MODE_DESCRIPTIONS[mode] || MODE_DESCRIPTIONS.assistant;
}

export function buildSystemPrompt({ timezone, mode = "assistant", userProfile = {} } = {}) {
  const tz = typeof timezone === "string" && timezone.trim() ? timezone.trim() : "Europe/Moscow";
  let dateLabel = "";
  try {
    dateLabel = new Intl.DateTimeFormat("ru-RU", {
      timeZone: tz,
      weekday: "long",
      year: "numeric",
      month: "long",
      day: "numeric"
    }).format(new Date());
  } catch {
    dateLabel = new Intl.DateTimeFormat("ru-RU", {
      timeZone: "Europe/Moscow",
      weekday: "long",
      year: "numeric",
      month: "long",
      day: "numeric"
    }).format(new Date());
  }

  const base = MODE_PROMPTS[mode] || MODE_PROMPTS.assistant;
  const parts = [base];

  if (mode === "assistant") {
    if (userProfile?.style === "short") {
      parts.push("Отвечай максимально лаконично: строго 1–2 коротких предложения по сути.");
    } else if (userProfile?.style === "detailed") {
      parts.push("Отвечай обстоятельно и развёрнуто: 4–6 предложений с полезными деталями.");
    } else {
      parts.push("Обычно используй 1–3 коротких предложения.");
    }
  }

  if (userProfile?.name) {
    parts.push(`Пользователя зовут ${userProfile.name} (используй имя уместно и ненавязчиво).`);
  }

  if (userProfile?.city) {
    parts.push(`Город пользователя по умолчанию: ${userProfile.city}.`);
  }

  parts.push(`Сегодняшняя дата: ${dateLabel}.`);
  return parts.join(" ");
}
